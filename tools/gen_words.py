#!/usr/bin/env python3
"""Generate the Wordle word lists used by both the firmware and the Unraid server.

Inputs
  tools/all_valid_words.txt   every 5-letter word accepted as a guess (one per line)

Method
  * "answers" are the most common words from that list, ranked with the `wordfreq`
    package, with simple plural / past-tense / profanity filtering.
  * "guesses" is every valid word (a superset of the answers).

Outputs
  wordle-server/data/answers.txt   alphabetical, one per line
  wordle-server/data/guesses.txt   alphabetical, one per line (includes answers)
  firmware/src/words.h             the same data as flash-resident fixed-width tables

Run:  pip install wordfreq better-profanity && python3 tools/gen_words.py
You only need to re-run this if you want to change the lists. Edit EXTRA_EXCLUDE or
ANSWER_COUNT below, or replace all_valid_words.txt, and regenerate.
"""
import json
import math
import pathlib
import sys

from better_profanity import profanity
from wordfreq import zipf_frequency

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "all_valid_words.txt"
ANSWER_COUNT = 2300
MIN_ZIPF = 3.3
# Words you never want as a daily answer (they stay valid as guesses).
# The source list includes names, brands, places and slang; these were removed by hand
# after reviewing the frequency-ranked candidates. Add more here and re-run if you spot
# any you don't like.
EXTRA_EXCLUDE = set("""
allan allen anglo ariel barca barry bates benny betty billy bobby bowie brent brock bubba
buffy burke butch calif chang chevy ching clint cohen colin congo corey costa craig darcy
danny della denis devon diana diane dixie dover doris erica emery fedex felix fella fritz
garth gemma garde hogan harry henry hicks homer honda india intel inter intra james japan
jenny jerry jesse jesus jimmy jolie jones judas julia kelly kerry kirby kraft kylie kyrie
laura leone levin lewis linux logan louie louis lowry lynch malik mamma mandy manny maria
mitch molly monte monty moran morse moses nancy nazis niger nicky norma ollie oscar paolo
paris parry patel patty pedro peggy pepsi perry peter pluto pratt putin quran ralph ramon
randy riley roche roger roman romeo rowan rubin rubio rufus sally sammy santo sears shawn
shiva silva sloan smith sonny spain starr sudan tammy terra terry tesla texas tommy torah
tyler wales wally weber welch welsh wigan yahoo yates venus hydra mecca jihad haram china
chile greek dutch swiss gypsy sexes crore facto versa vitro forex avant hella gonna gotta
wanna kinda outta gimme dunno legit admin synod blanc cisco yikes bible
""".split())
# Day -> answer index permutation multiplier (must be coprime with the answer count).
MULTIPLIER = 7919
OFFSET = 13


def looks_inflected(w: str) -> bool:
    """Heuristic: drop plain plurals and past tenses so answers feel like 'real' words."""
    if w.endswith("s") and not w.endswith(("ss", "us", "is")):
        if zipf_frequency(w[:-1], "en") > 3.0:
            return True
    if w.endswith("ed"):
        if zipf_frequency(w[:-2], "en") > 3.0 or zipf_frequency(w[:-1], "en") > 3.0:
            return True
    return False


def main() -> int:
    valid = sorted({w.strip().lower() for w in SRC.read_text().split() if len(w.strip()) == 5 and w.strip().isalpha()})
    profanity.load_censor_words()

    ranked = []
    for w in valid:
        if w in EXTRA_EXCLUDE or profanity.contains_profanity(w) or looks_inflected(w):
            continue
        z = zipf_frequency(w, "en")
        if z >= MIN_ZIPF:
            ranked.append((z, w))
    ranked.sort(key=lambda t: (-t[0], t[1]))
    answers = sorted(w for _, w in ranked[:ANSWER_COUNT])
    n = len(answers)
    if math.gcd(MULTIPLIER, n) != 1:
        print(f"MULTIPLIER {MULTIPLIER} is not coprime with answer count {n}; change one of them", file=sys.stderr)
        return 1

    guesses = sorted(set(valid) | set(answers))

    data = ROOT / "wordle-server" / "data"
    data.mkdir(parents=True, exist_ok=True)
    # The server reads these so its daily word always matches the firmware's tables.
    (data / "params.json").write_text(json.dumps({
        "answers": n,
        "multiplier": MULTIPLIER,
        "offset": OFFSET,
        "epoch": [2021, 6, 19],
    }, indent=2) + "\n")
    (data / "answers.txt").write_text("\n".join(answers) + "\n")
    (data / "guesses.txt").write_text("\n".join(guesses) + "\n")

    def table(name: str, words) -> str:
        lines = []
        for i in range(0, len(words), 16):
            chunk = "".join(words[i:i + 16])
            lines.append(f'    "{chunk}"')
        return f"static const char {name}[] PROGMEM =\n" + "\n".join(lines) + ";\n"

    header = (
        "// AUTO-GENERATED by tools/gen_words.py - do not edit by hand.\n"
        "// Fixed-width tables: every word is exactly 5 lowercase letters, no separators,\n"
        "// sorted alphabetically (so binary search works directly on flash).\n"
        "#pragma once\n#include <stdint.h>\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n"
        f"#define WORDS_ANSWER_COUNT {n}\n"
        f"#define WORDS_GUESS_COUNT {len(guesses)}\n"
        f"#define WORDS_DAY_MULTIPLIER {MULTIPLIER}\n"
        f"#define WORDS_DAY_OFFSET {OFFSET}\n\n"
        + table("WORDS_ANSWERS", answers) + "\n" + table("WORDS_GUESSES", guesses)
    )
    fw = ROOT / "firmware" / "src"
    fw.mkdir(parents=True, exist_ok=True)
    (fw / "words.h").write_text(header)

    sample = ", ".join(answers[:: max(1, n // 12)])
    print(f"valid guesses: {len(guesses)}  answers: {n}  (min zipf {ranked[min(ANSWER_COUNT, len(ranked)) - 1][0]:.2f})")
    print("sample answers:", sample)
    return 0


if __name__ == "__main__":
    sys.exit(main())
